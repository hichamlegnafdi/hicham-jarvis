import os
import webbrowser
import subprocess
import json
from datetime import datetime
from pathlib import Path
from core.system_control import SystemController

try:
    from core.file_control import FileController
    file_ctrl = FileController()
except ImportError:
    file_ctrl = None

controller = SystemController()

PERMISSION_LEVELS = {
    "OPEN_APP": 1, "CLOSE_APP": 1, "SEARCH_WEB": 1, 
    "OPEN_YOUTUBE": 1, "OPEN_WEBSITE": 1, "SET_REMINDER": 1,
    "MUTE": 2, "SLEEP": 3, "READ_FILE": 1, "LIST_DIR": 1, 
    "CREATE_FILE": 2, "BATTERY_STATUS": 1, "RUN_POWERSHELL": 3,
    "SET_BRIGHTNESS": 2, "KILL_APP": 2, "SYSTEM_STATUS": 1,
    "READ_CLIPBOARD": 1, "SEND_WHATSAPP": 2, "GET_WEATHER": 1, "GET_CRYPTO_PRICE": 1,
    "GET_MARKET_NEWS": 1, "GET_ASSET_PRICE": 1,
    "ADD_SCHEDULE": 1, "GET_SCHEDULE": 1,
    # أمر المبرمج الذاتي الجديد:
    "AUTO_CODE": 3  # مستوى حماية عالي حيت كينفذ كود بايثون
}

def is_safe_path(target_path):
    try:
        abs_path = Path(target_path).resolve()
        forbidden_paths = [Path("C:/Windows"), Path("C:/Program Files"), Path("C:/Program Files (x86)")]
        for forbidden in forbidden_paths:
            if forbidden in abs_path.parents or abs_path == forbidden:
                return False
        return True
    except:
        return False

def execute(action_name: str, action_args: str = "") -> str:
    if not action_name:
        return "Aucune action."
        
    action_name = action_name.upper().strip()
    action_args = action_args.strip() if isinstance(action_args, str) else str(action_args)

    if PERMISSION_LEVELS.get(action_name, 0) == 0:
        return f"❌ إجراء مرفوض."

    try:
        # ----------------------------------------------------
        # المبرمج الذاتي (Auto-Coder) 💻
        # ----------------------------------------------------
        if action_name == "AUTO_CODE":
            # Gemini غيكتب الكود هنا، حنا غنحفظوه فملف مؤقت ونفذوه
            code_snippet = action_args
            # إيلا صيفط ليك الكود وسط علامات الاقتباس، نحيدوهوم
            code_snippet = code_snippet.replace("```python", "").replace("```", "").strip()
            
            script_path = "data/autogenerated_script.py"
            os.makedirs("data", exist_ok=True)
            
            with open(script_path, "w", encoding="utf-8") as f:
                f.write(code_snippet)
                
            # تنفيذ السكريبت بـ Python والتقاط النتيجة
            result = subprocess.run(["python", script_path], capture_output=True, text=True, timeout=10)
            
            if result.returncode == 0:
                output = result.stdout.strip()
                return f"تم تنفيذي الكود بنجاح. النتيجة:\n{output if output else 'تم التنفيذ بدون مخرجات نصية.'}"
            else:
                error = result.stderr.strip()
                return f"❌ خطأ أثناء تنفيذ الكود البرمجي:\n{error}"
        # ----------------------------------------------------

        elif action_name == "ADD_SCHEDULE":
            parts = action_args.split("|", 1)
            if len(parts) == 2:
                time_str, task = parts[0].strip(), parts[1].strip()
                schedule_file = "data/schedule.json"
                os.makedirs("data", exist_ok=True)
                schedule_data = []
                if os.path.exists(schedule_file):
                    with open(schedule_file, "r", encoding="utf-8") as f:
                        try: schedule_data = json.load(f)
                        except: pass
                schedule_data.append({"time": time_str, "task": task, "done": False})
                with open(schedule_file, "w", encoding="utf-8") as f:
                    json.dump(schedule_data, f, ensure_ascii=False, indent=4)
                return f"تمت إضافة الموعد: {task} بتاريخ ووقت: {time_str}"
            return "❌ خطأ في الصيغة."

        elif action_name == "GET_SCHEDULE":
            schedule_file = "data/schedule.json"
            if not os.path.exists(schedule_file): return "الجدول فارغ."
            with open(schedule_file, "r", encoding="utf-8") as f:
                try: schedule_data = json.load(f)
                except: return "خطأ."
            tasks = [f"- {item['time']}: {item['task']}" for item in schedule_data if not item.get("done")]
            return "المهام المجدولة:\n" + "\n".join(tasks) if tasks else "لا توجد مهام حالياً."

        elif action_name == "GET_ASSET_PRICE":
            import yfinance as yf
            ticker_symbol = action_args.upper().replace(' ', '')
            if not ticker_symbol: ticker_symbol = "^GSPC" 
            ticker = yf.Ticker(ticker_symbol)
            data = ticker.history(period="1d")
            if not data.empty:
                return f"السعر لـ {ticker_symbol} هو {round(data['Close'].iloc[-1], 4)}."
            return f"❌ لم يتم العثور على {ticker_symbol}"

        elif action_name == "GET_MARKET_NEWS":
            import requests
            from bs4 import BeautifulSoup
            query = action_args.replace(' ', '+') if action_args else "economy+markets"
            res = requests.get(f"https://news.google.com/rss/search?q={query}&hl=en-US&gl=US&ceid=US:en")
            soup = BeautifulSoup(res.content, features="xml")
            news_items = soup.findAll("item")
            if not news_items: return "لم أجد أي أخبار."
            headlines = [f"- {item.title.text}" for item in news_items[:3]]
            return f"أحدث الأخبار:\n" + "\n".join(headlines)
        
        elif action_name == "GET_WEATHER":
            import requests
            city = action_args if action_args else "Sale,Morocco"
            res = requests.get(f"https://wttr.in/{city}?format=%t+%C")
            return f"الطقس في {city}: {res.text}"
            
        elif action_name == "GET_CRYPTO_PRICE":
            import requests
            crypto = action_args.lower() if action_args else "bitcoin"
            res = requests.get(f"https://api.coingecko.com/api/v3/simple/price?ids={crypto}&vs_currencies=usd")
            price = res.json().get(crypto, {}).get("usd", "غير متوفر")
            return f"سعر {crypto} هو: {price} USD."

        elif action_name == "READ_CLIPBOARD":
            import pyperclip
            return f"محتوى الحافظة: {pyperclip.paste()}"
            
        elif action_name == "SEND_WHATSAPP":
            import pywhatkit
            parts = action_args.split("|", 1)
            if len(parts) == 2:
                pywhatkit.sendwhatmsg_instantly(parts[0].strip(), parts[1].strip(), wait_time=15, tab_close=True)
                return f"تم الإرسال."
            return "❌ خطأ."
        
        elif action_name in ["OPEN_APP", "CLOSE_APP", "MUTE", "SLEEP", "BATTERY_STATUS"]:
            return controller.execute_command(action_name, action_args)
            
        elif action_name == "RUN_POWERSHELL":
            result = subprocess.run(["powershell", "-Command", action_args], capture_output=True, text=True)
            return f"✅ تم: {result.stdout.strip()}" if result.returncode == 0 else f"❌ خطأ: {result.stderr.strip()}"
        
        elif action_name == "SET_BRIGHTNESS":
            ps_cmd = f"(Get-WmiObject -Namespace root/WMI -Class WmiMonitorBrightnessMethods).WmiSetBrightness(1, {action_args})"
            subprocess.run(["powershell", "-Command", ps_cmd], capture_output=True)
            return f"تم."

        elif action_name == "KILL_APP":
            ps_cmd = f"Stop-Process -Name {action_args} -Force -ErrorAction SilentlyContinue"
            subprocess.run(["powershell", "-Command", ps_cmd], capture_output=True)
            return f"تم إغلاق {action_args}."

        elif action_name == "SYSTEM_STATUS":
            ps_cmd = "Get-CimInstance Win32_OperatingSystem | Select-Object FreePhysicalMemory,TotalVisibleMemorySize"
            res = subprocess.run(["powershell", "-Command", ps_cmd], capture_output=True, text=True)
            return f"الموارد:\n{res.stdout.strip()}"
            
        elif action_name == "SEARCH_WEB":
            webbrowser.open(f"https://www.google.com/search?q={action_args.replace(' ', '+')}")
            return f"تم."
            
        elif action_name == "OPEN_YOUTUBE":
            import pywhatkit
            pywhatkit.playonyt(action_args)
            return f"تم."
            
        elif action_name == "OPEN_WEBSITE":
            webbrowser.open(action_args if action_args.startswith("http") else f"https://{action_args}")
            return f"تم."
            
        elif action_name == "SET_REMINDER":
            os.makedirs("data", exist_ok=True)
            with open("data/reminders.txt", "a", encoding="utf-8") as f:
                f.write(f"{action_args}\n")
            return f"تم."

        elif action_name == "READ_FILE":
            return file_ctrl.read_file(action_args) if is_safe_path(action_args) else "❌ منع أمني."
            
        elif action_name == "LIST_DIR":
            path = action_args if action_args else "."
            return file_ctrl.list_directory(path) if is_safe_path(path) else "❌ منع أمني."
            
        elif action_name == "CREATE_FILE":
            parts = action_args.split("|", 1)
            return file_ctrl.create_file(parts[0].strip(), parts[1].strip() if len(parts)>1 else "") if is_safe_path(parts[0]) else "❌ منع أمني."

    except Exception as e:
        return f"❌ خطأ: {str(e)}"
        
    return "❌ لم يتم التعرف على الأمر."